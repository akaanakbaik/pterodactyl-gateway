import { readdirSync, readFileSync, statSync } from "node:fs";
import { join, relative } from "node:path";

const roots = ["src", "test", "scripts", "examples"];
const files = [];
const errors = [];

function collect(directory) {
  for (const entry of readdirSync(directory)) {
    const path = join(directory, entry);
    if (statSync(path).isDirectory()) {
      collect(path);
      continue;
    }
    if (/\.(?:ts|js|mjs|cjs)$/.test(path) && !path.endsWith("source-guard.js")) files.push(path);
  }
}

for (const root of roots) collect(root);

const COMMENT_PATTERN = /^\s*(?:\/\/|\/\*|\*\/|\*\s)|[^:"'`]\/\/\s|<!--/;
const WATERMARK_PATTERN = /codebuff|freebuff|generated by ai|chatgpt|claude/i;
const CREDENTIAL_PATTERN = /(?:ptla|ptlc|ghp|sk-[A-Za-z0-9])_[A-Za-z0-9]{20,}/g;

for (const path of files) {
  const content = readFileSync(path, "utf8");
  const lines = content.split("\n");
  lines.forEach((line, index) => {
    const trimmed = line.trim();
    if (trimmed.startsWith("#!")) return;
    if (COMMENT_PATTERN.test(line)) {
      errors.push(`${relative(process.cwd(), path)}:${index + 1} berisi komentar kode.`);
    }
  });
  if (WATERMARK_PATTERN.test(content)) {
    errors.push(`${relative(process.cwd(), path)} berisi watermark atau atribusi pihak ketiga.`);
  }
  if (/TODO|FIXME|HACK:/.test(content)) {
    errors.push(`${relative(process.cwd(), path)} masih memiliki penanda pekerjaan yang belum selesai.`);
  }
  const matches = content.match(CREDENTIAL_PATTERN) ?? [];
  for (const value of matches) {
    if (!/^(?:ptla|ptlc)_x+$/.test(value)) {
      errors.push(`${relative(process.cwd(), path)} berisi pola kredensial yang tidak diizinkan.`);
      break;
    }
  }
}

if (errors.length) {
  console.error("Source guard gagal:");
  errors.forEach(error => console.error(`- ${error}`));
  process.exit(1);
}

console.log(`Source guard OK: ${files.length} file diperiksa.`);
